'use strict';

// Links recordings in assets/audio to the adhkar they belong to.
// Usage: node scripts/audio-sync.cjs          (rewrites src/data/audio.generated.ts)
//        node scripts/audio-sync.cjs --check  (fails if the file is out of date)
// A recording is named after its dhikr, for example assets/audio/tasbih.m4a.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const folder = path.join(root, 'assets', 'audio');
const target = path.join(root, 'src', 'data', 'audio.generated.ts');
const adhkar = JSON.parse(fs.readFileSync(path.join(root, 'src', 'data', 'adhkar.json'), 'utf8'));
const MAX_BYTES = 2 * 1024 * 1024;
const EXTENSIONS = ['.m4a', '.mp3', '.aac', '.wav'];

/** Every recording the app can play, in the order the guide lists them. */
const KNOWN = [
  'sayyid-al-istighfar',
  ...adhkar.items.find((item) => item.id === 'after-prayer-tasbih').steps.map((step) => step.id),
  'astaghfirulloh',
];

function generate() {
  const files = fs.existsSync(folder) ? fs.readdirSync(folder).filter((name) => !name.startsWith('.') && name !== 'README.md').sort() : [];
  const problems = [];
  const entries = [];
  for (const name of files) {
    const extension = path.extname(name).toLowerCase();
    const id = path.basename(name, path.extname(name));
    if (!EXTENSIONS.includes(extension)) { problems.push(`${name}: format ${EXTENSIONS.join(', ')} bo‘lishi kerak.`); continue; }
    if (!KNOWN.includes(id)) { problems.push(`${name}: noma’lum nom. Ruxsat etilgan nomlar: ${KNOWN.join(', ')}.`); continue; }
    if (entries.some((entry) => entry.id === id)) { problems.push(`${name}: «${id}» uchun ikkinchi fayl. Bittasini qoldiring.`); continue; }
    const size = fs.statSync(path.join(folder, name)).size;
    if (size === 0 || size > MAX_BYTES) { problems.push(`${name}: fayl bo‘sh bo‘lmasin va 2 MB dan oshmasin (hozir ${size} bayt).`); continue; }
    entries.push({ id, name });
  }
  if (problems.length) throw new Error(`Audio fayllarda xato:\n- ${problems.join('\n- ')}`);
  entries.sort((a, b) => KNOWN.indexOf(a.id) - KNOWN.indexOf(b.id));
  const lines = entries.map((entry) => `  '${entry.id}': require('../../assets/audio/${entry.name}'),`);
  return `// Generated by scripts/audio-sync.cjs from the files in assets/audio. Do not edit by hand.
// Add a recording by placing it in assets/audio (see assets/audio/README.md) and running: npm run audio:sync
export const AUDIO_IDS = ${JSON.stringify(KNOWN)} as const;
export type AudioId = (typeof AUDIO_IDS)[number];

export const ADHKAR_AUDIO: Partial<Record<AudioId, number>> = {
${lines.join('\n')}${lines.length ? '\n' : ''}};
`;
}

const output = generate();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error('src/data/audio.generated.ts eskirgan. `npm run audio:sync` ni ishga tushiring.');
    process.exit(1);
  }
  console.log('Audio list is up to date.');
} else {
  fs.writeFileSync(target, output);
  console.log(`Audio: ${(output.match(/require\(/g) || []).length} recording(s) linked.`);
}
